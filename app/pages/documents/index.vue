    <h2 style="margin:36px 0 14px">Группа 1. Перевозка: что оформляется на каждый рейс</h2>
    <p><b>Транспортная накладная.</b> Основной перевозочный документ, форма утверждена постановлением Правительства РФ от 21.12.2020 № 2200. Именно она подтверждает заключение договора перевозки конкретного груза между конкретными точками — а не «акт выполненных работ», как в аренде крана. Старая товарно-транспортная накладная по форме 1-Т обязательна только для отдельных категорий грузов (прежде всего алкогольной продукции); в остальных случаях её оформляют дополнительно, по договорённости сторон.</p>
    <p><b>Путевой лист.</b> Состав сведений и порядок оформления установлены приказом Минтранса России от 28.09.2022 № 390 — он действует с 1 марта 2023 года. Путевой лист подтверждает законность выезда машины на линию и фиксирует предрейсовый контроль; заказчику он на руки не передаётся, но по запросу мы показываем его наличие.</p>
    <p><b>Что меняется 1 сентября 2026 года.</b> С этой даты транспортная накладная оформляется в электронном виде через государственную систему электронных перевозочных документов (ГИС ЭПД) — требование введено Федеральным законом от 07.06.2025 № 140-ФЗ. Если накладная проведена через систему, бумажный экземпляр для проверки на дороге и для налоговой не нужен. Для заказчика-юрлица это означает, что закрывающий документ по доставке приходит в электронный документооборот, а не «водитель завезёт на следующей неделе».</p>

