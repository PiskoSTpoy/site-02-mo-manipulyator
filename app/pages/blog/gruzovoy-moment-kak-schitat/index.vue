    <h2 style="margin-bottom:18px">Формула: M = G × L</h2>
    <p>Грузовой момент (M) — это произведение массы груза (G) на вылет стрелы (L, расстояние от оси поворота крана до точки, где висит груз). Измеряется в тонно-метрах (т·м) и обычно указывается производителем в виде грузовой диаграммы — таблицы или графика «масса ↔ вылет» для конкретной модели КМУ.</p>
    <p>Смысл формулы простой: чем дальше нужно опустить груз от машины, тем меньше масса, которую манипулятор способен удержать при том же грузовом моменте. Это объясняет, почему техника с одинаковым паспортным тоннажом на кузове может по-разному справляться с одной и той же задачей — если у одной модели грузовой момент выше, у неё больше запас на увеличенном вылете.</p>

    <h2 style="margin:36px 0 18px">Пример расчёта</h2>
    <p>Возьмём типовую задачу: нужно переместить груз массой 2 тонны на расстояние 4 метра от манипулятора — например, через ограждение участка, куда машина не может подъехать вплотную. Требуемый грузовой момент считается по той же формуле: M = G × L = 2 т × 4 м = 8 т·м. Это значит, что для этой задачи подходит техника с паспортным грузовым моментом от 8 т·м и выше — не любой манипулятор, формально способный поднять 2 тонны у борта.</p>
    <p>Формула работает и в обратную сторону — если известен грузовой момент конкретной машины, можно посчитать, какую массу она поднимет на нужном вылете: G = M ÷ L. Например, при грузовом моменте 10 т·м и вылете 8 метров максимальная масса груза — 10 ÷ 8 = 1,25 тонны, заметно меньше, чем у самого борта машины.</p>

