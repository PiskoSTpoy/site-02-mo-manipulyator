    <h2 style="margin:36px 0 18px">Когда достаточно манипулятора</h2>
    <p>Если груз едет с базы или склада и его нужно выгрузить на объекте, а одна единица груза не тяжелее того, что КМУ поднимает на нужном вылете. Это поддоны кирпича и блоков, мешки, пиломатериал и брус, фундаментные блоки ФБС и небольшие плиты, бытовки, контейнеры, малая спецтехника. Сколько таких поддонов встаёт на борт и сколько проходит по массе, мы считали <a href="/blog/skolko-poddonov-v-manipulyator/">отдельно</a>.</p>
    <p>Второй сильный аргумент — подъезд. Узкая улица в СНТ, двор жилого дома, участок за кюветом: двухосный манипулятор с бортом 2,17 м проходит там, где 12-метровый автокран с опорным контуром почти 5 × 5,6 м просто не развернётся. Если груз лёгкий, но класть его нужно далеко от дороги, трёхосная машина с длинной стрелой кладёт его на 18,7 м без заезда на участок.</p>

    <h2 style="margin:36px 0 18px">Когда без автокрана не обойтись</h2>
    <p>Первый случай — масса. Всё, что тяжелее 7 т в одной единице, выходит за пределы нашего парка при любом вылете, а на реальном рабочем вылете в 6–8 м граница ещё ниже: Palfinger PK 23500A на 8 м поднимает 2 730 кг. Тяжёлые железобетонные элементы, ёмкости, блочные трансформаторные подстанции, крупное оборудование массой больше 7 т — это автокран.</p>
    <p>Второй — высота. Подать материал на кровлю трёх-четырёхэтажного здания, смонтировать конструкцию на высоте 15–20 м — задача для стрелы автокрана в 21–30 м: даже самая длинная КМУ нашего парка на конце стрелы поднимает 300 кг.</p>
    <p>Третий — объём подъёмов без перевозки. Если материал уже лежит на площадке и весь день нужно только поднимать и монтировать, возить на борту нечего, и главное преимущество манипулятора пропадает.</p>

    <h2 style="margin:36px 0 18px">Как считать деньги</h2>
    <p>Сравнивать нужно не ставку за час, а стоимость всей задачи. У манипулятора это одна машина: ставка нашего парка — от 7 500 ₽ за смену у класса до 3 т и от 18 000 ₽ у класса 10–20 т, плюс километраж от МКАД. У автокрана к смене крана добавляется отдельный грузовик на доставку, а у московских арендодателей типичен минимальный заказ 7 часов работы плюс 1 час подачи — даже если сам подъём занимает двадцать минут. Для разовой доставки с выгрузкой это почти всегда дороже. Для монтажа, где машина работает всю смену, счёт выравнивается, и решает уже не цена, а физика — масса и высота.</p>
    <p>Общее для обеих машин — пропуска. Полная масса трёхосного манипулятора (24–24,8 т) и 25-тонного автокрана (20,5–21,5 т) выше 12 т, поэтому на МКАД и внутрь неё днём обеим нужен грузовой пропуск — мы разбирали это в <a href="/blog/propusk-mkad-ttk-gruzovik/">статье про пропуска</a>. Двухосные ИТ-80 (8,18 т) и Soosan SCS334 (7,5 т) под этот порог не попадают.</p>

