    <h2 id="strahovanie" style="margin:36px 0 18px">Страхование манипулятора</h2>
    <p>Статья 637 ГК РФ возлагает обязанность страховать транспортное средство и (или) ответственность за причинённый им ущерб на арендодателя. Условие одно: страхование обязательно, только когда это требует закон или сам договор аренды. Если ни закон, ни договор страхование не требуют, арендодатель манипулятора МАНИП-МО не обязан страховать машину по умолчанию.</p>
    <p>Заказчику манипулятора МАНИП-МО на этом этапе стоит спросить одно: распространяется ли на конкретную машину обязательное страхование гражданской ответственности как источника повышенной опасности и действует ли оно на дату выезда. Полис — не формальность, а прямое следствие статьи 640 о вреде третьим лицам, разобранной ниже.</p>

    <h2 id="subarenda" style="margin:36px 0 18px">Субаренда и договоры с третьими лицами</h2>
    <p>Статья 638 ГК РФ разрешает арендатору без согласия арендодателя сдавать манипулятор в субаренду и заключать с третьими лицами договоры перевозки. Условие одно: эти договоры не должны противоречить целям использования машины, указанным в договоре аренды, а если цели не определены — её обычному назначению. Норма диспозитивна: договор аренды манипулятора МАНИП-МО вправе прямо запретить субаренду, и тогда действует запрет, а не общее правило.</p>
    <p>На практике для разовой доставки манипулятором МАНИП-МО субаренда почти не встречается — заказчик работает напрямую. Статья 638 ГК РФ актуальна для подрядчиков, которые привлекают манипулятор как часть своего договора с конечным заказчиком: закон не требует отдельного согласования этой цепочки с арендодателем техники, если цель использования машины не меняется.</p>

    <h2 id="uscherb" style="margin:36px 0 18px">Ущерб технике и вред третьим лицам</h2>
    <p>Два разных риска при работе манипулятора МАНИП-МО — повреждение самой машины и вред, причинённый ею окружающим, — ГК РФ регулирует по-разному. Статья 639 требует от арендатора возместить ущерб технике только тогда, когда арендодатель докажет, что потеря или повреждение произошли по обстоятельствам, за которые отвечает арендатор. Бремя доказывания лежит на арендодателе, а не на заказчике — это снимает с заказчика риск спора «докажи, что ты не виноват».</p>
    <p>Статья 640 ГК РФ возлагает ответственность за вред третьим лицам — транспортному средству другого участника движения, имуществу или здоровью — на арендодателя: манипулятор МАНИП-МО при аренде с экипажем не выходит из его владения в смысле главы 59 ГК РФ об источнике повышенной опасности. У арендодателя остаётся право регрессного требования к арендатору, если вред возник по его вине, но первым перед пострадавшим отвечает владелец машины, а не заказчик рейса.</p>

