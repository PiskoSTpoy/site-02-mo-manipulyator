    <h2 id="chto-takoe" style="margin-bottom:18px">Что такое аренда ТС с экипажем</h2>
    <p>Статья 632 ГК РФ определяет договор аренды транспортного средства с экипажем как соглашение, по которому арендодатель предоставляет ТС за плату во временное владение и пользование. Своими силами он же оказывает услуги по управлению машиной и по её технической эксплуатации. Манипулятор МАНИП-МО подходит под эту формулировку буквально: заказчик получает не голую машину, а машину вместе с оператором, который ею управляет.</p>
    <p>Отличие от обычной аренды, глава 34 § 1 ГК РФ, в том, что там арендатор сам отвечает за управление вещью. Манипулятор МАНИП-МО без оператора в аренду не сдаёт — значит, к каждому заказу применяется именно § 3 главы 34, а не общие нормы об аренде транспорта без экипажа.</p>

