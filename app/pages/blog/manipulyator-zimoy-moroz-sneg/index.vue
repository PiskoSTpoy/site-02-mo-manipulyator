    <p>Предел по паспорту КМУ — это верхняя граница, а не разрешение работать до неё с любым грузом. Бытовка, сэндвич-панели или лист профнастила на крюке ведут себя как парус и разворачиваются даже при ветре слабее паспортного. Поэтому для парусных грузов МАНИП-МО сверяет прогноз ветра накануне и при порывах переносит выгрузку — подробнее о бытовках на странице <a href="/gruzy/bytovka-i-vagonchik/">бытовки и вагончика</a>.</p>

