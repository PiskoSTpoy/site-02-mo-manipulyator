    <p>Подъезд к участку в СНТ зимой зависит от товарищества: внутренние дороги по закону № 217-ФЗ — имущество общего пользования, и чистит их СНТ. Трёхосные Kanglim KS1256G-II ({{ String(ks.gvwT).replace('.', ',') }} т) и Palfinger PK 23500A ({{ String(pk.gvwT).replace('.', ',') }} т) по нечищеной улице не пойдут. ИНМАН ИТ-80 шириной {{ it80.bodyW }} проходит там, где расчищена одна колея. Как устроен допуск техники в СНТ, разобрано в статье <a href="/blog/snt-dopusk-manipulyator/">про манипулятор и СНТ</a>.</p>
