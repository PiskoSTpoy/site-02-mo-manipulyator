    <h2 id="progrev" style="margin:36px 0 18px">Прогрев гидравлики перед работой</h2>
    <p>Руководство по эксплуатации КМУ Palfinger — производителя установки PK 23500A из парка МАНИП-МО — задаёт особый порядок пуска при температуре воздуха ниже −10 °C. Коробку отбора мощности включают на минимальных оборотах двигателя и несколько минут прокачивают гидравлическую жидкость, не нагружая установку. То же руководство требует, чтобы гидравлическая жидкость была предназначена для работы при температуре ниже 0 °C.</p>
    <p>Для заказчика манипулятора прогрев означает одно: первые минуты после приезда машина стоит на опорах и не поднимает груз. На морозе ниже −10 °C прогрев входит в смену МАНИП-МО так же, как установка опор. Торопить оператора КМУ с первым подъёмом бессмысленно: холодная гидравлика двигает стрелу рывками, а рывок с грузом на вылете опаснее задержки.</p>

    <h2 id="snegopad" style="margin:36px 0 18px">Снегопад и туман: когда работу останавливают</h2>
    <p>Пункт 132 ФНП № 461 останавливает работу КМУ при снегопаде, дожде или тумане в тот момент, когда оператор плохо различает сигналы стропальщика или перемещаемый груз. Норма привязана не к количеству осадков, а к видимости, поэтому одна и та же метель останавливает одну выгрузку и не мешает другой. Решение принимает оператор МАНИП-МО на месте, а не диспетчер по прогнозу.</p>
