    <h2 style="margin-bottom:18px">Что запрещает знак и что разрешает исключение</h2>
    <p>Знак 3.4 запрещает движение грузовых автомобилей и составов транспортных средств с разрешённой максимальной массой более 3,5 т — если под знаком нет дополнительной таблички с другим числом, — а также тракторов и самоходных машин. Кран-манипуляторная установка на грузовом шасси попадает в эту категорию точно так же, как обычный борт: с точки зрения знака это грузовой автомобиль, а не спецтехника со своим отдельным режимом.</p>
    <p>Приложение 1 к ПДД тут же задаёт исключение, которым живёт вся логистика внутри таких зон: знак 3.4 не запрещает движение транспортных средств организаций федеральной почтовой связи, а также грузовых автомобилей без прицепа с разрешённой максимальной массой не более 26 т, которые обслуживают предприятия, находящиеся в обозначенной зоне. При этом такие машины должны въезжать в зону и выезжать из неё на ближайшем к месту назначения перекрёстке — то есть исключение не даёт права ездить по зоне произвольно, оно даёт право доехать кратчайшим путём до конкретного адреса и тем же путём выехать.</p>

    <h2 style="margin:36px 0 18px">Кто попадает под исключение без вопросов</h2>
