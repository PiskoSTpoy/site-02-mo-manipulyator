    <h2 style="margin:36px 0 18px">Серая зона: частный дом, СНТ и коттеджный посёлок</h2>
    <p>Для типового рейса манипулятора точка разгрузки — не предприятие, а участок в садовом товариществе или коттеджном посёлке: плита, блок ФБС или кольцо колодца едут частному заказчику, а не на баланс юридического лица. Формально частный дом — не «предприятие», и буквальное прочтение Приложения 1 оставляет открытым вопрос, распространяется ли исключение на такую доставку вообще. Устоявшейся судебной практики именно по этой развилке — предприятие или частное домовладение — в открытых источниках нет, и делать вид, что вопрос закрыт в чью-то пользу, было бы нечестно.</p>
    <p>Практический вывод из этой неопределённости простой: если единственный доступный путь к участку в старой части посёлка или в СНТ проходит через зону знака 3.4, разумно заранее иметь при себе документ на груз — товарно-транспортную накладную или УПД, где адрес доставки совпадает с точкой внутри зоны, — и въезжать строго через ближайший к этому адресу перекрёсток, а не выбирать путь короче в объезд. Это не гарантия от штрафа при буквальном толковании, но именно то, что снимает вопрос об умышленном транзите через ограниченную зону не по делу.</p>

