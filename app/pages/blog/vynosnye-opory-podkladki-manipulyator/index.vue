    <h2 id="raschet" style="margin:36px 0 18px">Площадь подкладки: формула и пример</h2>
    <p>Руководство по эксплуатации КМУ Palfinger даёт формулу: площадь опоры A (см²) равна реакции опоры (Н), делённой на несущую способность грунта (Н/см²). Реакцию опоры указывает техническое описание конкретной модели КМУ. Для Palfinger PK 23500A и других машин парка МАНИП-МО эту цифру оператор берёт из документации своей установки.</p>
    <p>Пример расчёта для подкладки манипулятора МАНИП-МО ниже построен на условной реакции опоры 80 кН — это 80 000 Н. Цифра взята для наглядности, а не из паспорта конкретной КМУ. Чем слабее грунт, тем больше сторона квадратной подкладки:</p>
    <ul>
      <li>плотный крупный песок, 60 Н/см²: 80 000 / 60 ≈ 1 333 см² — квадрат около 37 × 37 см;</li>
      <li>влажный мелкий песок средней плотности, 20 Н/см²: 80 000 / 20 = 4 000 см² — около 63 × 63 см;</li>
      <li>суглинок с пористостью 1,0 и показателем текучести 1, 10 Н/см²: 80 000 / 10 = 8 000 см² — около 90 × 90 см.</li>
    </ul>
    <p>Руководство КМУ Palfinger отдельно предупреждает про подкладки собственного изготовления: они не должны разрушаться под нагрузкой. Трухлявая доска или пустотелый блок под опорой манипулятора МАНИП-МО опаснее, чем отсутствие подкладки, потому что проседают внезапно. Опорная пята, ушедшая в грунт, по тому же руководству может опрокинуть машину.</p>

