    <h2 style="margin-bottom:18px">Почему КМУ выше обычного борта</h2>
    <p>Сам факт установки крана-манипулятора на шасси прибавляет высоту конструктивно, а не по недосмотру производителя. Поворотная колонна, сложенные в транспортное положение секции стрелы и гидравлический бак стоят сразу за кабиной и у большинства моделей не опускаются ниже её крыши — в отличие от простого борта без надстройки, где самая высокая точка машины — сама кабина. Насколько именно установка поднимает общий габарит, зависит от модели КМУ и высоты самого шасси, и единой цифры «на все манипуляторы» не существует: точное значение габаритной высоты указано в паспорте конкретной машины, и смотреть нужно именно туда, а не в память о прошлом похожем рейсе.</p>
    <p>Тот же принцип работает и в обратную сторону: два внешне похожих манипулятора на разных шасси — например, с низкорамной и со стандартной рамой — могут отличаться по высоте на десятки сантиметров. Именно эти сантиметры на знаке с запасом в несколько десятков сантиметров и решают, пройдёт конкретная машина под конкретным путепроводом или нет.</p>

    <h2 style="margin:36px 0 18px">Что на самом деле означает цифра на знаке</h2>
    <p>Знак 3.13 относится к запрещающим знакам Приложения 1 к ПДД и запрещает движение транспортных средств, габаритная высота которых — с грузом или без — больше указанной на знаке величины. На первый взгляд логика простая: высота манипулятора меньше цифры на знаке — путь свободен. Проблема в том, что сама эта цифра не равна фактическому расстоянию от покрытия до низа конструкции: технические требования к применению дорожных знаков закладывают между реальным габаритом сооружения и значением на знаке запас — порядка 0,3 м там, где путепровод несёт автомобильную дорогу, и около 0,4 м там, где сверху проходит железная дорога. Этот запас рассчитан на неровность дорожного покрытия и погрешность измерения самого сооружения, а не на то, что у водителя остаётся лишний зазор сверх цифры на знаке.</p>
    <p>Отсюда практический вывод: манипулятор, чья паспортная высота равна цифре на знаке или отличается от неё на несколько сантиметров, проезжать под этим путепроводом не стоит — запас уже израсходован самим нормативом, водителю сверху добавить нечего.</p>

    <h2 style="margin:36px 0 18px">Штраф — не главная цена ошибки</h2>
    <p>За несоблюдение требований знака 3.13 водителю грозит предупреждение либо штраф по части 1 статьи 12.16 КоАП РФ — с 1 января 2025 года он составляет 750 ₽. Федеральный закон от 26.12.2024 № 490-ФЗ поднял в полтора раза штрафы по целому ряду статей КоАП, включая эту; до этого действовала прежняя сумма 500 ₽, и материалы, где она ещё встречается, попросту не обновлялись после этой поправки. Сама по себе эта сумма несравнима с тем, что происходит при фактическом ударе стрелой или кабиной о конструкцию путепровода.</p>
    <p>Повреждение сооружения — отдельная история, и регулируется она не КоАП, а общими основаниями гражданской ответственности: по статье 1064 ГК РФ вред, причинённый имуществу, подлежит возмещению в полном объёме лицом, которое его причинило. На практике это оплата ремонта или экспертизы путепровода, простой техники и вызов аварийных служб для разбора застрявшей машины, а если авария перекрыла движение — ещё и издержки перед заказчиком, для которого застрявший на маршруте манипулятор означает не доехавший вовремя груз.</p>

    <h2 style="margin:36px 0 18px">Где эта цифра могла измениться за последний год</h2>
    <p>Опасность знака 3.13 в том, что водитель склонен доверять маршруту, которым уже проезжал раньше, а не проверять высоту заново перед каждым рейсом. В Подмосковье это особенно рискованно именно сейчас: за последние годы на Ярославском направлении в Мытищах, в километре от МКАД, построен путепровод «Фрунзе — Мира» через железнодорожные пути — там, где раньше был переезд в одном уровне без всякого ограничения по высоте, сегодня стоит новое сооружение со знаком 3.13. Похожая стройка идёт и на других направлениях Подмосковья, где путепроводы через железную дорогу либо появляются заново, либо меняют габарит при капитальном ремонте старого моста.</p>
    <p>Практический вывод для диспетчера и водителя один: маршрут с путепроводами в городах ближнего пояса, где активно идёт или недавно закончилась дорожная стройка, нельзя считать неизменным по умолчанию. Высоту по знаку и паспортную высоту конкретной машины стоит сверять перед каждым рейсом, а не только при первом проезде по новому адресу — это тот же принцип, что и в расчёте <NuxtLink to="/blog/gruzovoy-moment-kak-schitat/">грузового момента по паспорту установки</NuxtLink>: решение принимается по документу, а не на глаз.</p>

