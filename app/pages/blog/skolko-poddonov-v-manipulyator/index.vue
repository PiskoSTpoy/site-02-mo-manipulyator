    <p>Главный вывод из двух таблиц: на двухосных машинах площадь борта под тяжёлые поддоны используется на треть или меньше. Два поддона кирпича по 2 т — это уже работа для трёхосной машины, а не два рейса «газели», и по деньгам это обычно выгоднее. Разница в классах и ставках — на странице <a href="/park/">парка</a>. Когда машина гружена под паспорт, дальше вступают ограничения маршрута: пропуск в пределах МКАД для машин полной массой больше 12 т (<a href="/blog/propusk-mkad-ttk-gruzovik/">разбор</a>) и знаки нагрузки на ось на подъезде (<a href="/blog/znak-3-12-nagruzka-na-os-manipulyator/">про знак 3.12</a>).</p>

