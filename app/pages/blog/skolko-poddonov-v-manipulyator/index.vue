    <h2 style="margin-bottom:18px">Шаг 1. Какие бывают поддоны</h2>
    <p>Деревянные поддоны в России делают по ГОСТ 33757-2016. Стандарт знает три типоразмера: 1200×800 мм (европоддон, на нём чаще всего приходят кирпич, мешки и тротуарная плитка), 1200×1000 мм (финский, на нём часто везут блоки) и 1200×1200 мм. Пустой поддон 1200×800 весит не больше 40 кг, 1200×1000 — не больше 45 кг.</p>
    <p>Важнее другое: стандарт ограничивает и массу брутто. Для поддона 1200×800 это 1 000 кг, если на нём один крупный груз или мешки, и 1 250 кг, если на нём ящики, не скреплённые между собой; для 1200×1000 — 1 350 кг. Кирпичные заводы при этом отгружают поддоны тяжелее: по таблицам поставщиков поддон одинарного кирпича 250×120×65 мм (420–480 шт.) весит 2 000–2 100 кг, полуторного 250×120×88 мм (320–360 шт.) — 1 800–1 900 кг, двойного — до 1 500 кг. Поэтому для расчёта рейса берём массу из накладной, а не «номинал поддона».</p>
    <p>Отдельная ловушка — газобетон. Марка D500 означает среднюю плотность около 500 кг/м³ в сухом состоянии, и кажется, что поддон 1,8 м³ весит 900 кг. Но блоки уходят с завода влажными — по данным Bonolit, после автоклава влажность достигает 30%, — и реальный поддон тяжелее этой оценки. Если в накладной массы нет, закладывайте запас.</p>

