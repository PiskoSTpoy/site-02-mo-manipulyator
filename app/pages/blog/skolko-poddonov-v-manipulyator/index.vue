    <p>Как вылет и масса складываются в одну цифру — грузовой момент, — разобрано в <a href="/blog/gruzovoy-moment-kak-schitat/">отдельной статье</a>. На практике достаточно назвать расстояние от места, где встанет машина, до точки укладки: класс машины подбирается под самый дальний и самый тяжёлый поддон, а не под средний.</p>

    <h2 style="margin:36px 0 18px">Что прислать, чтобы посчитать рейс без ошибки</h2>
    <p>Четыре вещи: тип и количество поддонов (1200×800 или 1200×1000), масса одного поддона из накладной поставщика, расстояние от места постановки машины до точки укладки и фото подъезда. По этим данным сразу видно, укладывается ли заказ в один рейс и какой машиной. Больше про типовые грузы — на странице <a href="/gruzy/poddony-i-meshki/">поддонов и мешков</a>.</p>

