    <h2 id="trebovaniya-k-lyulke" style="margin:36px 0 18px">Требования к люльке и стропам</h2>
    <p>Пункт 238 ФНП № 461 требует, чтобы люлька использовалась только по своему паспорту и имела документ о соответствии по статье 7 закона № 116-ФЗ. Ограждение — жёсткие перила высотой не менее 1 100 мм по всему периметру, сплошные до высоты 0,5 м. Высота от пола до любой перекладины или крыши люльки — не менее 2 м. Дверь не открывается наружу и запирается автоматическим замком. Пол выдерживает вдвое больше паспортной грузоподъёмности люльки и имеет дренажные отверстия. Ни одно из этих требований не выполняет грузовая площадка, поддон или ковш — поэтому в МАНИП-МО их для людей не используют.</p>
    <p>Пункт 239 ФНП № 461 отдельно ограничивает стропы для подвеса люльки. Коэффициент запаса прочности — не менее 8 у цепных стропов и не менее 10 у канатных; у колец и скоб для подвеса на крюк — тоже не менее 10. Текстильные стропы для люльки запрещены, как и обжимные втулки на концах канатов. Стропы люльки не используют для других грузов — поэтому обычный комплект строп с борта манипулятора МАНИП-МО для подвеса людей не годится.</p>

    <h2 id="poryadok-podema" style="margin:36px 0 18px">Как проходит подъём по пункту 241</h2>
    <p>Пункт 241 ФНП № 461 запрещает работу с люлькой при ветре сильнее 10 м/с, в дождь, снег, туман и при обледенении. Подъём идёт под непосредственным руководством инженерно-технического работника, ответственного за безопасное производство работ. Оператор КМУ всё время видит люльку и места её подъёма и опускания и не совмещает движения крана — например, не поворачивает стрелу одновременно с подъёмом.</p>
    <p>Между оператором и людьми в люльке по пункту 241 ФНП № 461 должна быть постоянная радио- или телефонная связь. Порядок обмена сигналами утверждает распорядительный акт эксплуатирующей организации. Люди в люльке заранее расписываются в инструктаже, пристёгнуты страховочными привязями к точкам крепления внутри люльки, не встают на перила и не используют подставки. Раскачивание гасят оттяжками, а люльку, стропы и крюк осматривают перед каждым использованием. Такой объём организации — отдельная работа с ответственными лицами, а не опция к рейсу манипулятора МАНИП-МО с доставкой груза.</p>

    <h2 id="avtovyshka" style="margin:36px 0 18px">Когда вместо манипулятора нужна автовышка</h2>
