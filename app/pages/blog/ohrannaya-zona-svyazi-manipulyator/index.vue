    <p>Вторая типичная ситуация — свежая застройка. Новые коттеджные посёлки и логистические объекты в Московской области подключают к связи одновременно со строительством, и подрядчик прокладывает кабель ровно там, где потом естественно встанет техника на разгрузку, — вдоль забора или у въезда на площадку, в первую же неделю после сдачи объекта, когда ни план сетей, ни памятная табличка ещё не дошли до всех, кто приезжает на объект.</p>

