    <h2 style="margin-bottom:18px">Правило: 2 метра от кабеля, и никаких визуальных подсказок</h2>
    <p>Охранная зона трассы подземной кабельной линии связи, согласно Правилам охраны линий и сооружений связи Российской Федерации, утверждённым постановлением Правительства РФ от 09.06.1995 № 578, — это полоса земли, ограниченная параллельными прямыми, отстоящими от кабеля не менее чем на 2 метра с каждой стороны. На трассах, где кабель проложен вне населённых пунктов на открытых, безлесных участках, эта ширина задаётся именно так; в стеснённых условиях застройки конкретная привязка делается по трассировочному чертежу линии, который есть у эксплуатирующей организации. На местности зона должна быть обозначена предупредительными знаками с надписью «Копать запрещается, охранная зона кабеля» — но это требование к оператору связи, а не гарантия того, что знак дожил до сегодняшнего дня в целости.</p>
