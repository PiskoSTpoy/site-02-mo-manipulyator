    <h2 style="margin:36px 0 18px">Что запрещено без согласования и в какой срок вызывать представителя</h2>
    <p>Правила прямо запрещают производить земляные работы в охранной зоне кабельной линии связи до прибытия представителя предприятия, эксплуатирующего эту линию. Обязанность здесь лежит на стороне, которая планирует работы: не позднее чем за 3 дня до начала работ, исключая выходные и праздничные дни, нужно вызвать представителя оператора связи для технического надзора — он на месте определяет точное положение кабеля и глубину его залегания по исполнительной документации и шурфованием, если нужно. Пока это не сделано, вскрывать грунт в зоне нельзя.</p>
    <p>Правила защищают обе стороны, а не только оператора связи: если представитель не явился по вызову в срок, расходы на простой техники и рабочих возмещает уже само предприятие связи — по соглашению сторон или через суд. То есть процедура двусторонняя, и вызов представителя — это не формальность в пользу оператора, а способ снять риск для обеих сторон одновременно.</p>

    <h2 style="margin:36px 0 18px">Почему это касается именно опоры манипулятора, а не колёс грузовика</h2>
    <p>Правила 1995 года ничего не говорят про выносные опоры кран-манипуляторных установок — документ такую технику не имел в виду. Но здесь работает та же логика, что и в нашем разборе охранной зоны газопровода: значение имеет не факт проезда, а характер нагрузки на грунт. Гружёный борт передаёт вес через четыре-шесть колёс, распределённых по всей длине шасси, и для кабеля, залегающего на нормативной глубине, это обычно не критично. Аутригер манипулятора работает иначе: вся боковая нагрузка от поднятого груза уходит в грунт через одну опорную плиту площадью в десятки сантиметров, а на мягком или переувлажнённом участке под неё дополнительно подсыпают и выравнивают площадку — то есть выполняют операцию, которая перестаёт быть просто стоянкой и становится вмешательством в верхний слой грунта именно там, где может проходить кабель.</p>
    <p>Практический вывод для нас простой: если единственное свободное место для установки опор попадает в двухметровую полосу от обозначенного или предполагаемого кабеля, а грунт под опорой требует подготовки, вопрос закрывается вызовом представителя заранее, а не выбором понадеяться, что кабель проложен глубже, чем достаёт опора.</p>

