    <p>Граница здесь не абсолютная. Если манипулятор простоял во дворе с выпущенными опорами дольше, чем объективно требует сама разгрузка, — например, ждёт, пока освободится площадка для складирования плит, — формальное основание считать это уже стоянкой, а не разгрузкой, появляется. Единой цифры в минутах, которая разделяла бы «ещё работаем» и «уже стоим», в правилах нет, и делать вид, что вопрос закрыт, было бы нечестно.</p>

    <h2 style="margin:36px 0 18px">Сколько стоит ошибка</h2>
