    <p>Одноразовый мягкий контейнер по п. 3.1.4 ГОСТ ISO 21898-2013 рассчитан на одно наполнение и не ремонтируется. Перегрузка с борта манипулятора МАНИП-МО на участок — часть того же рейса, а мешок, который на участке высыпали и наполнили снова, поднимать уже нельзя. Поставщику пункт 125 ФНП № 461 предписывает грузить так, чтобы при разгрузке мешки можно было безопасно застропить: петли сверху, без перекоса.</p>

