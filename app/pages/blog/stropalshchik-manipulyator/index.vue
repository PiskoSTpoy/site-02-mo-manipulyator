    <p>Пункт 129 ФНП № 461 добавляет запрет, который чаще всего нарушают на тесных участках: нельзя находиться между поднимаемым грузом и стеной, штабелем, вагоном или другим оборудованием. Правило действует при подъёме, перемещении и опускании. Если манипулятор МАНИП-МО ставит пачку бруса вплотную к стене дома, стропальщик направляет её оттяжкой сбоку, а не встаёт в зазор.</p>

    <h2 id="signaly" style="margin:36px 0 18px">Сигналы и сигнальщик</h2>
    <p>Пункт 248 ФНП № 461 обязывает эксплуатирующую организацию установить порядок обмена сигналами между стропальщиком и оператором КМУ, а сами жесты приведены в приложении № 7. При смене участка работы оператора МАНИП-МО и стропальщика заново инструктируют под подпись о сигнализации, принятой на новом месте, — так требует п. 249.</p>
    <p>Сигнальщик по п. 153 ФНП № 461 нужен, когда зона работы манипулятора не просматривается с места управления, а радио- или телефонной связи между оператором и стропальщиком нет. Назначают сигнальщика из числа стропальщиков. На участке в СНТ это типичная картина: Kanglim KS1256G-II из парка МАНИП-МО стоит на улице, а груз уходит за дом, где оператор его уже не видит.</p>
    <p>Погода тоже упирается в сигналы: п. 132 ФНП № 461 требует прекратить работу при снегопаде, дожде или тумане, когда оператор плохо различает сигналы стропальщика или сам груз. Для манипулятора это не формальность — на вылете 15–18 м жест стропальщика в метель не виден, и работу МАНИП-МО в такой момент останавливает, а не продолжает «на слух».</p>

    <h2 id="zakazchiku" style="margin:36px 0 18px">Что сделать заказчику до приезда машины</h2>
    <p>Заказчику МАНИП-МО до приезда машины нужно сделать 3 вещи, чтобы строповка не сорвала выгрузку. Первое — уточнить при заявке, будет ли оператор КМУ работать один или нужен второй стропальщик на месте укладки. Второе — назвать массу каждого места груза: без неё п. 114 ФНП № 461 подъём запрещает. Третье — показать, где груз ляжет и видно ли это место от машины.</p>
    <p>Остальное на площадке делает персонал с допуском. Хозяин участка или прораб заранее убирает людей и машины из зоны под стрелой, показывает место укладки и не подходит к грузу, пока тот висит на крюке. Если место укладки не видно с улицы, связь между стропальщиками и оператором МАНИП-МО организует по радио или через сигнальщика по п. 153.</p>

