    <h2 id="poryadok" style="margin:36px 0 18px">Порядок подъёма по ФНП № 461</h2>
    <p>Пункт 114 ФНП № 461 задаёт первый шаг любого подъёма: груз отрывают на 0,2–0,3 м и останавливают, чтобы проверить строповку и тормоз. Только после этой паузы оператор КМУ МАНИП-МО ведёт груз дальше. Стропальщику пункт разрешает стоять возле груза, пока тот поднят не выше 1 м от площадки, — выше этой отметки он отходит из-под груза.</p>
    <p>Тот же п. 114 ФНП № 461 запрещает поднимать груз неизвестной массы, поэтому МАНИП-МО просит указать в заявке массу из накладной или паспорта изделия. Кирпич на поддоне без ограждения пункт разрешает перемещать только при разгрузке на землю или погрузке с земли. Подать такой поддон на перекрытие или через высокий забор нельзя — нужна тара или ограждение.</p>
    <ol>
      <li>Стропальщик выбирает стропы по массе груза и схеме строповки, цепляет груз и отходит.</li>
