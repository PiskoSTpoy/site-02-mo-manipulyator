    <h2 id="kto-vprave" style="margin-bottom:18px">Кто вправе цеплять груз на крюк</h2>
    <p>Пункт 216 ФНП № 461 требует квалификацию «стропальщик» от любого работника, который навешивает груз на крюк подъёмного сооружения, зацепляет или обвязывает его. Кран-манипулятор — такое же подъёмное сооружение, поэтому правило действует на каждой выгрузке КМУ в МАНИП-МО, от ИНМАН ИТ-80 до Kanglim KS1256G-II. Должность и опыт работника значения не имеют: прораб, грузчик и владелец участка без этой квалификации к строповке не допускаются.</p>
    <p>Отдельной строкой п. 216 ФНП № 461 закрывает частую лазейку «там же петли, обвязывать нечего». Тот же уровень квалификации нужен, когда груз подвешивают без обвязки: за петли, рымы и цапфы, в бадье, контейнере или другой таре. На выгрузке МАНИП-МО кольцо колодца с монтажными петлями, блок ФБС и биг-бэг с песком цепляет стропальщик, а не тот, кто оказался рядом с машиной.</p>
    <p>Исключение в том же п. 216 узкое: зацепку без предварительной обвязки разрешено поручать обученному и проинструктированному персоналу только для подъёмных сооружений, управляемых с пола. Обвязку стропами пачки бруса или поддона это исключение не покрывает ни для какого крана. Для заказчика МАНИП-МО практический вывод один: на выгрузке должен быть стропальщик с удостоверением.</p>

    <h2 id="sovmeshchenie" style="margin:36px 0 18px">Оператор КМУ и стропальщик в одном лице</h2>
    <p>ФНП № 461 не запрещают одному работнику совмещать работу оператора крана-манипулятора и стропальщика. Условие одно — у человека должны быть обе квалификации, а эксплуатирующая организация назначает его на обе работы внутренним распорядительным актом: список должностей, которые назначаются приказом, приведён в п. 151. Поэтому на рынке и встречается связка «водитель — оператор КМУ — стропальщик» в одном лице, и при заявке в МАНИП-МО это уточняют заранее.</p>
    <p>Совмещение работает, пока оператор КМУ видит груз и может сам его зацепить и отцепить. У ИНМАН ИТ-80 из парка МАНИП-МО вылет {{ it80.reach }}, и при разгрузке рядом с бортом оператор успевает застропить груз, отойти к пульту и поднять его. У Kanglim KS1256G-II вылет {{ ks.reach }}: груз опускается за забором или за домом, и отцепить его там одному оператору уже не получится — на месте укладки нужен второй стропальщик.</p>
