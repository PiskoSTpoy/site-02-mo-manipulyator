    <p>В пакете МАНИП-МО инструкция оператора КМУ и инструкция стропальщика различаются по обязанностям: первый отвечает за машину и грузовой момент, второй — за строповку и сигналы. Попросите не сами тексты, а лист ознакомления с датами и подписями. Это занимает минуту и отделяет компанию с порядком от компании, которая знает правила только устно.</p>

