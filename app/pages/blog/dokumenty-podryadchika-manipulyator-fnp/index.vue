    <h2 id="kto-naznachaet" style="margin-bottom:18px">Кто назначает оператора и стропальщика: п. 151</h2>
    <p>Пункт 151 ФНП № 461 возлагает на эксплуатирующую организацию обязанность назначить машинистов подъёмников, крановщиков (операторов), их помощников и стропальщиков внутренним распорядительным актом. Слова «распорядительным актом» означают приказ, а не устную договорённость с диспетчером. Для МАНИП-МО это значит, что оператор на конкретной машине работает по приказу компании-владельца.</p>
    <p>Список в пункте 151 шире, чем экипаж: рабочие люльки, слесари, электромонтёры и наладчики назначаются тем же актом. Заказчику от МАНИП-МО нужна одна строка: кто в день рейса стоит у рычагов и кто строповит груз, и есть ли для них приказ. Если на площадке работает стропальщик-помощник, его назначение проверяется по тому же пункту.</p>

