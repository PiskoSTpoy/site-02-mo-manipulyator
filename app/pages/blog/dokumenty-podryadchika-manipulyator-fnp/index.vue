    <p>Пункт 136 относит к ПС, которые работают на собственном источнике энергии, и кранов-манипуляторов. Для МАНИП-МО практический вопрос такой: в паспорте машины, которую присылают на объект, есть ли последняя запись о пуске и дата технического освидетельствования. Сроки освидетельствования разобраны в статье <a href="/blog/tekhosvidetelstvovanie-manipulyatora-sroki/">про техосвидетельствование КМУ</a>.</p>

