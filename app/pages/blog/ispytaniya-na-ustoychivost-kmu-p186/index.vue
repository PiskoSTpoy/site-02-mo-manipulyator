    <h2 id="kak" style="margin:36px 0 18px">Как проходит испытание</h2>
    <p>Пункт 188 ФНП № 461 задаёт одно условие: испытывать нужно в таком положении и исполнении внутри рабочей зоны, где устойчивость крана минимальна. Если паспорт задаёт разные нагрузки для разных положений или зон, испытание проводят для выбора этих условий. У манипулятора Kanglim KS1256G-II с вылетом 18,7 м и 300 кг на 20,7 м самым неблагоприятным обычно будет длинный вылет, но конкретную точку выбирает руководство по эксплуатации, а не редакция МАНИП-МО.</p>
