    <p>Пункт 186 ФНП № 461 говорит о «стреловом самоходном кране», а пункт 175 перечисляет краны стрелового типа и краны-манипуляторы как две группы. Прямого слова «манипулятор» в пункте 186 нет. МАНИП-МО не делает из этого вывода «испытание не нужно»: если в паспорте манипулятора указаны характеристики устойчивости, пункт 169 «г» всё равно подключает испытание к полному освидетельствованию, а пункт 187 допускает не повторять его.</p>
