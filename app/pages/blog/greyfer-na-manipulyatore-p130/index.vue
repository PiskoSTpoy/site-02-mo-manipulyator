    <h2 id="gruzopodemnost" style="margin:36px 0 18px">Грузоподъёмность с грейфером: пункт 84</h2>
    <p>Пункт 84 ФНП № 461 касается крана, который уже в эксплуатации и при реконструкции получает моторный грейфер или грузовой электромагнит: полезную грузоподъёмность ограничивают по таблице приложения № 1. Коэффициент ограничения зависит от группы классификации по паспорту: 0,3 для групп A3–A4, 0,75 для A5–A6 и 1,0 для A7 и выше. МАНИП-МО не переводит эти коэффициенты в килограммы для конкретных машин: способ расчёта ФНП не расписывает, и цифру даёт проект реконструкции.</p>
    <p>Тот же пункт 84 ФНП № 461 требует перенастроить ограничитель грузоподъёмности и регистратор параметров либо поставить новые приборы. Ограничитель не требуется, только если полезная грузоподъёмность после реконструкции не превышает 50 % паспортной. Отдельно запрещено оснащать грузовым электромагнитом кран, в зоне работы которого есть производственные или другие помещения. МАНИП-МО читает это как прямой ответ на вопрос «можно ли магнитом во дворе у дома».</p>

