    <h2 style="margin:34px 0 14px">При чём здесь допуск оператора</h2>
    <p>Способ управления — не только эксплуатационное удобство, но и предмет тех же ФНП, что уже определяют требования к ограничителям и регистраторам параметров: системы дистанционного управления подъёмными сооружениями подчиняются тем же правилам монтажа, наладки и учёта в паспорте ПС, что и остальные приборы безопасности установки (подробный разбор этого раздела ФНП — в статье про устройство КМУ). А то, что оператор обязан пройти обучение и получить удостоверение именно на эксплуатацию конкретной установки, включая её систему управления, — тема <NuxtLink to="/blog/attestaciya-operatora-kmu/">отдельной статьи про допуск оператора КМУ</NuxtLink>, которую мы не пересказываем здесь второй раз.</p>

    <h2 style="margin:34px 0 14px">Что из этого важно для заявки</h2>
    <p>Ни компоновка, ни способ управления не входят в стоимость смены — цена по-прежнему считается по классу грузоподъёмности и километражу в <NuxtLink to="/#konfigurator">конфигураторе</NuxtLink>. Но обе детали стоит проговорить заранее, если задача нетиповая: длинномерный груз вроде бруса выигрывает от компоновки между кабиной и кузовом (страница про <NuxtLink to="/gruzy/srub-i-brus/">сруб и брус</NuxtLink> объясняет, почему это критично), а разгрузка с узкого проезда задним ходом — от заднего расположения стрелы и точной работы радиоуправления, как в сценарии <NuxtLink to="/keysy/dostavka-v-zakrytyy-posyolok/">доставки в закрытый посёлок</NuxtLink>. Для контейнера и малой спецтехники, где машина обычно грузит и разгружает прицеп, расширенная рабочая зона заднего расположения тоже играет в плюс — это можно уточнить на странице груза <NuxtLink to="/gruzy/konteyner/">«Контейнер»</NuxtLink>.</p>

    <h2 style="margin:34px 0 14px">Коротко</h2>
    <ul>
      <li>Компоновка «между кабиной и кузовом» освобождает борт под длинномерные грузы и делает машину компактнее в развороте.</li>
      <li>Заднее расположение стрелы расширяет рабочую зону: погрузка прицепа, работа задним ходом в узком проезде — в обмен на свободное место под длинномер на борту.</li>
      <li>Ширина выносных опор задаётся станиной и шасси, а не положением стрелы — компоновка влияет на то, что удобно возить, а не на то, встанет ли машина на участке.</li>
      <li>Способ управления — рычаги или радио — не зависит от компоновки: это отдельное решение производителя на этапе сборки установки.</li>
      <li>Радиоуправление даёт точность, скорость и автоматическое отключение при потере сигнала, но заметно дороже в комплектации (150–800 тыс. ₽) и сложнее в ремонте.</li>
      <li>Ни один из этих параметров не входит в цену смены напрямую — но оба стоит уточнить заранее для нетиповой задачи.</li>
    </ul>

