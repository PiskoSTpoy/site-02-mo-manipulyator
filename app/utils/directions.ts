// Направления по шоссе, а не по административным единицам.
//
// Почему так: заказчик манипулятора в Подмосковье не думает «Одинцовский округ» —
// он думает «55 км по Новориге». Плечо считается по трассе от МКАД, и именно
// километр по конкретному шоссе, а не название района, попадает в счёт.
//
// Расстояния — из сводной таблицы расстояний от МКАД (сверено 12.08.2026),
// округлены так же, как в источнике. Точный километраж конкретного адреса
// берётся из маршрута при расчёте заявки.

// Явный импорт, а не автоимпорт Nuxt: тариф должен быть один на весь сайт,
// и относительный путь гарантирует, что модуль резолвится и вне контекста Nuxt
// (например, при прогоне типов).
