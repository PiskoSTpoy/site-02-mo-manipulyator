// Ось сайта — груз, а не «услуга». Заказчик манипулятора формулирует заявку словами
// «нужно привезти брус» или «нужно снять контейнер», а не «нужна услуга доставки
// с разгрузкой». Отсюда и структура: /gruzy/<что везём>.
//
// Поле `limiter` — главное, ради чего этот файл существует: у каждого груза свой
// физический ограничитель (масса / длина / вылет / габарит), и он почти никогда
// не совпадает с тем, что заказчик называет в заявке.

export type CargoType = {
  slug: string
  /** Как груз называет заказчик */
  name: string
  /** Короткий подзаголовок для карточки */
  tagline: string
  /** Что реально отсекает технику по этому грузу */
  limiter: string
  /** Класс, с которого имеет смысл начинать подбор */
  startClass: string
  /** Типовая масса одного подъёма */
  unitMass: string
  /** Габарит, который решает */
  unitSize: string
}

