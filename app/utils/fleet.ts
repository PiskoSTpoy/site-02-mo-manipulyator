export type FleetRow = {
  id: string
  /** Класс по грузоподъёмности — то, как заявка формулируется заказчиком */
  cls: string
  /** Модель КМУ */
  kmu: string
  /** Шасси, на котором взяты паспортные габариты борта */
  chassis: string
  axles: number
  /** Полная масса ТС, т — решает вопрос пропуска на МКАД (порог 12 т) */
  gvwT: number
  /** Борт: длина, м (число — для сортировки) */
  bodyLm: number
  bodyL: string
  bodyW: string
  /** Что реально можно положить на борт */
  bodyLoad: string
  /** Грузовой момент, т·м */
  momentTm: number
  /** Максимальный вылет стрелы, м (число — для сортировки) */
  reachM: number
  reach: string
  /** Грузоподъёмность на минимальном вылете */
  capMin: string
  /** Грузоподъёмность на максимальном вылете */
  capMax: string
  /** Что этой машиной осмысленно возить */
  fit: string
  src: { label: string; href: string }
  note?: string
  /** Наша ставка от, ₽ за смену (8 ч) — равна SHIFT_RATE[cls], здесь не задублирована
   *  вручную, а взята той же ссылкой, чтобы цифра в таблице парка физически не могла
   *  разъехаться с калькулятором и тарифной таблицей (см. Волна 16 про разъезд ТТХ). */
  priceFrom: number
}

